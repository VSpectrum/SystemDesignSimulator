/**
 * Filter components using multi-token search against label, desc, category and tags.
 */
export function filterComponents(query: string): ComponentDefinition[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) {
    return COMPONENT_LIBRARY;
  }

  const terms = trimmed.split(/\s+/).filter(Boolean);

  return COMPONENT_LIBRARY.filter((item) => {
    return terms.every((term) => {
      if (item.label.toLowerCase().includes(term)) return true;
      if (item.desc.toLowerCase().includes(term)) return true;
      if (item.category.toLowerCase().includes(term)) return true;
      if (item.tags.some((tag) => tag.toLowerCase().includes(term))) return true;
      return false;
    });
  });
}
